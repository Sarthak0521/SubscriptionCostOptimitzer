from langchain.agents import create_agent
from langchain_ollama import ChatOllama

# Tool 1: Calculate annual subscription cost
def calculate_annual_cost(monthly_cost: float) -> str:
    """Calculate the annual cost of a monthly subscription."""
    annual_cost = monthly_cost * 12
    return f"Monthly cost: ₹{monthly_cost:.2f}\nAnnual cost: ₹{annual_cost:.2f}"

# Tool 2: Compare two subscription plans
def compare_plans(plan_a_cost: float, plan_b_cost: float) -> str:
    """Compare the monthly costs of two subscription plans."""
    if plan_a_cost == plan_b_cost:
        return (
            f"Plan A: ₹{plan_a_cost:.2f}/month\n"
            f"Plan B: ₹{plan_b_cost:.2f}/month\n"
            "Result: No difference. Both plans cost the same."
        )

    difference = abs(plan_a_cost - plan_b_cost)
    cheaper = "Plan A" if plan_a_cost < plan_b_cost else "Plan B"

    return (
        f"Plan A: ₹{plan_a_cost:.2f}/month\n"
        f"Plan B: ₹{plan_b_cost:.2f}/month\n"
        f"Result: {cheaper} is cheaper by ₹{difference:.2f}/month."
    )

# Create local Ollama model
model = ChatOllama(
    model="qwen2.5:3b",
    temperature=0
)

# Create agent
agent = create_agent(
    model=model,
    tools=[calculate_annual_cost, compare_plans],
    system_prompt="""
You are a Subscription Cost Optimizer.

Your job is to compare subscription plans accurately.

Rules:
1. Use calculate_annual_cost when annual cost is requested.
2. Use compare_plans when two plans need to be compared.
3. If both calculations are needed, use BOTH tools.
4. Never invent a price difference.
5. If two plans have exactly the same cost, clearly say:
   "There is no difference between the plans."
6. Give the final answer in a concise and understandable format.
"""
)

# Function to run a test and print the trace
def run_test(question: str):
    print("\n" + "=" * 70)
    print("USER QUESTION")
    print("=" * 70)
    print(question)
    print("\n" + "=" * 70)
    print("AGENT TRACE")
    print("=" * 70)

    result = agent.invoke({
        "messages": [
            {
                "role": "user",
                "content": question
            }
        ]
    })

    # Print every message generated by the agent
    for message in result["messages"]:
        print(f"\n[{type(message).__name__}]")

        if hasattr(message, "tool_calls") and message.tool_calls:
            for tool_call in message.tool_calls:
                print("Tool:", tool_call["name"])
                print("Arguments:", tool_call["args"])

        if hasattr(message, "content") and message.content:
            print("Content:", message.content)

    print("\n" + "=" * 70)
    print("FINAL ANSWER")
    print("=" * 70)
    print(result["messages"][-1].content)

# Test 1: Different-cost plans
run_test(
    """
Plan A costs ₹899999 per month and Plan B costs ₹799999 per month.
Calculate the annual cost of both plans and tell me which plan is
cheaper and how much I save per year.
"""
)

# Test 2: Equal-cost edge case
run_test(
    """
Plan A costs ₹500 per month and Plan B also costs ₹500 per month.
Calculate the annual cost of both plans and compare them.
Tell me whether either plan is cheaper.
"""
)